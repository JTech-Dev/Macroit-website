function setLanguage(language) {
  const selectedLanguage = translations[language] ? language : "es";

  document.documentElement.lang = selectedLanguage;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    const translation = translations[selectedLanguage][key];

    if (translation !== undefined) {
      element.textContent = translation;
    }
  });

  document.querySelectorAll("[data-i18n-content]").forEach((element) => {
    const key = element.dataset.i18nContent;
    const translation = translations[selectedLanguage][key];

    if (translation !== undefined) {
      element.setAttribute("content", translation);
    }
  });

  document.querySelectorAll("[data-language]").forEach((button) => {
    const isActive = button.dataset.language === selectedLanguage;

    button.setAttribute("aria-pressed", String(isActive));

    button.classList.toggle("bg-blue-600", isActive);
    button.classList.toggle("text-white", isActive);
    button.classList.toggle("shadow-sm", isActive);
    button.classList.toggle("text-gray-600", !isActive);
  });

  localStorage.setItem("macroit-language", selectedLanguage);
}

function initializeLanguage() {
  const savedLanguage = localStorage.getItem("macroit-language");

  const initialLanguage =
    savedLanguage && translations[savedLanguage] ? savedLanguage : "es";

  setLanguage(initialLanguage);

  document.querySelectorAll("[data-language]").forEach((button) => {
    button.addEventListener("click", () => {
      setLanguage(button.dataset.language);
    });
  });
}

document.addEventListener("DOMContentLoaded", initializeLanguage);
